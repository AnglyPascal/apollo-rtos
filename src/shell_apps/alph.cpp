void show(void *param)
{
  auto buf = (args_buffer_t *)param;
  auto str = buf->args;

  while (*str != '\0') {
    auto c = *str++;
    auto img = c == ','
                   ? comma
                   : (c == '.' ? period : (c == ' ' ? blank : alph[c - 'a']));
    display::show(img);
    sched::sleep(300);
    display::reset();
    sched::sleep(300);
    display::show(img);
  }

  display::reset();
}

