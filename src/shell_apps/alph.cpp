void *show(void *param)
{
  auto buf = (buffer *)param;
  auto str = buf->str + 5;

  while (*str != '\0') {
    auto c = *str++;
    auto img = alph[c - 'a'];
    display::show(img);
    sched::sleep(300);
    display::reset();
    sched::sleep(300);
    display::show(img);
  }

  display::reset();
  return param;
}

